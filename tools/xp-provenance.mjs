// Writes docs/xp-media-provenance.json + .md: every picture or video a scene
// (or a contact card) can show, where it comes from, what was done to it,
// and SHA-256 hashes of the original and of the file in the repo.
// Dev-only (the originals are on the author's machine).
//
//   cd tools && node xp-provenance.mjs

import { createHash } from 'node:crypto';
import { createReadStream, existsSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { ROOT } from './lib/gs.mjs';
import { POSTERS_SRC, GAMES_SRC, POSTERS, CLIPS } from './lib/xp-sources.mjs';

const sha = path => new Promise((resolve, reject) => {
  const hash = createHash('sha256');
  createReadStream(path).on('data', d => hash.update(d)).on('end', () => resolve(hash.digest('hex'))).on('error', reject);
});
const win = path => path.replace(/\//g, '\\');
const time = s => `${Math.floor(s / 60)}:${(s % 60).toFixed(1).padStart(4, '0')}`;

const rows = [];

for (const [date, file, topic] of POSTERS) {
  const original = POSTERS_SRC + file;
  const output = `assets/media/xp/posters/${date}.webp`;
  rows.push({
    output, kind: 'weekly poster (image)', scenes: 'facebook, instagram (stories), telegram, x/threads, snapchat/stories, spotify (cover); text-only: whatsapp, messenger, discord, mail',
    source: 'local original folder', original: win(original), part: '',
    treatment: 'resized (360 px wide portrait / 480 px wide landscape), WebP; no crop',
    status: 'final', caption: topic,
    originalSha256: existsSync(original) ? await sha(original) : 'missing', outputSha256: await sha(ROOT + output), bytes: statSync(ROOT + output).size
  });
}

for (const [id, file, parts, landscape, posterAt, caption] of CLIPS) {
  const original = GAMES_SRC + file;
  const originalSha256 = existsSync(original) ? await sha(original) : 'missing';
  const part = parts.map(([a, b]) => `${time(a)}–${time(b)}`).join(' + ');
  const reframe = landscape ? '16:9 picture kept whole, centred on a blurred copy of itself (9:16)' : 'scaled to 360×640 (already 9:16)';
  rows.push({
    output: `assets/media/xp/clips/${id}.mp4`, kind: 'game segment clip (video, silent)', scenes: 'tiktok, instagram (reel), youtube',
    source: 'local original folder', original: win(original), part,
    treatment: `trimmed (${part}), ${reframe}, 24 fps, H.264, audio removed`,
    status: 'final', caption, originalSha256, outputSha256: await sha(`${ROOT}assets/media/xp/clips/${id}.mp4`), bytes: statSync(`${ROOT}assets/media/xp/clips/${id}.mp4`).size
  });
  rows.push({
    output: `assets/media/xp/clips/${id}.webp`, kind: 'clip poster frame (image)', scenes: 'tiktok, instagram, youtube (also lite / reduced motion)',
    source: 'local original folder (via the clip)', original: win(original), part: `frame at ${posterAt}s of the clip`,
    treatment: 'one frame of the clip above, WebP', status: 'final', caption, originalSha256,
    outputSha256: await sha(`${ROOT}assets/media/xp/clips/${id}.webp`), bytes: statSync(`${ROOT}assets/media/xp/clips/${id}.webp`).size
  });
}

/* what else a scene or a card can show (not made by this work) */
const OTHER = [
  ['assets/img/logo-128.webp, logo-256.webp', 'the service logo (already in the repo)', 'every scene (avatars, rings, pins, the voice scene)', 'repo (existing site asset)', '', 'final'],
  ['link.gallery (content.json, runtime)', 'photos the admin chose for a link («صور المشهد»)', 'facebook, instagram, tiktok, youtube, snapchat, spotify… (first, when set)', 'the admin\'s own uploads (published media/)', '', 'final, admin-chosen'],
  ['contacts[].image (content.json, runtime)', 'the support person\'s photo', 'the support card', 'the admin\'s own upload', '', 'final, admin-chosen'],
  ['CSS gradients, CSS map, SVG icons, emoji, text', 'generated decoration (no photo)', 'every scene, the contact cards', 'generated / placeholder (CSS, SVG, emoji)', '', 'final (decoration, not content)'],
  ['tools/.cache/demo/media/* (TRIP, CONFERENCE, TOPIC, QUIZ, EXPLORE, WIDE, SQUARE, TALL)', 'generated gradient posters with a word (tools/demo.mjs)', 'local demo / screenshots only (e.g. the demo Instagram gallery)', 'generated / placeholder (SVG → WebP)', '', 'TEMPORARY DEMO CONTENT: never in the repo\'s published content, never on the live site']
];

const json = { generated: new Date().toISOString(), note: 'Nothing here comes from screenshots shared in chat: every picture/video is cut from the original files on E: / F: listed below.', files: rows, other: OTHER.map(([output, kind, scenes, source, original, status]) => ({ output, kind, scenes, source, original, status })) };
writeFileSync(`${ROOT}docs/xp-media-provenance.json`, `${JSON.stringify(json, null, 2)}\n`);

const md = [
  '# Scene media provenance',
  '',
  'Generated by `tools/xp-provenance.mjs` (with `tools/lib/xp-sources.mjs`, the same list `tools/build-xp-media.mjs` builds from).',
  'Every picture and video a scene or a contact card can show. **Nothing comes from screenshots shared in chat**: the posters and clips are cut from the original files below. SHA-256 of the original lets anyone check the source.',
  '',
  '## Files in the repo (final)',
  '',
  '| Output | Kind | Source (original) | Part | Treatment | SHA-256 (original) |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows.map(r => `| \`${r.output}\` | ${r.kind} — «${r.caption}» | ${r.original} | ${r.part || '—'} | ${r.treatment} | \`${r.originalSha256}\` |`),
  '',
  '## Everything else a scene can show',
  '',
  '| What | Kind | Where | Source | Status |',
  '| --- | --- | --- | --- | --- |',
  ...OTHER.map(([output, kind, scenes, source, , status]) => `| ${output} | ${kind} | ${scenes} | ${source} | ${status} |`),
  '',
  'Output hashes (SHA-256 of the files in the repo) are in `docs/xp-media-provenance.json`.',
  ''
].join('\n');
writeFileSync(`${ROOT}docs/XP-MEDIA-PROVENANCE.md`, md);
console.log(`${rows.length} files; ${rows.filter(r => r.originalSha256 === 'missing').length} originals missing`);
readFileSync(`${ROOT}docs/XP-MEDIA-PROVENANCE.md`, 'utf8');
