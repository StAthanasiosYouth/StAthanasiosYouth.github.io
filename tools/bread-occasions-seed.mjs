#!/usr/bin/env node
/*
 * «خبزنا اليومي» P5 — the one-time seed of «مناسبات كنيستنا» (daily-bread/saints/occasions-seed.json, the list the
 * owner approved on 2026-11-25) → worker/migrations/0037_occasions.sql.
 *
 *   node bread-occasions-seed.mjs            write the migration
 *   node bread-occasions-seed.mjs --check    the migration in the repo is the list (exit 1 if not)
 *
 * - BREAD_OCCASIONS = '0' (the switch stays off until the owner decides).
 * - The new occasions: INSERT OR IGNORE (a second run changes nothing; nothing saved in the admin is overwritten).
 * - «إيبارشية البحر الأحمر» (P2): its P5 form only while nobody touched it (no `type` yet); rev + 1, so the review shows it.
 * - Abu Sefein's praise: the tamgeed sung in church (owner 2026-11-25, avarewase.org) in place of the madih P2 took from
 *   St-Takla — only while it is still that page; rev + 1 too. Nothing reaches the site before «راجع وانشر».
 * Every occasion is checked with the Worker's own rules against the published registry's people.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { checkOccasion, checkPerson } from '../worker/src/bread/saints.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const SRC = path.join(ROOT, 'daily-bread', 'saints', 'occasions-seed.json');
export const OUT = path.join(ROOT, 'worker', 'migrations', '0037_occasions.sql');
const BY = 'P5 seed';
const OLD_PRAISE = 'Tamgeed-AlShahied-Abo-Thefein-4';
const q = s => "'" + String(s).replace(/'/g, "''") + "'";

export function seedSql(seed, people) {
  const errs = seed.occasions.flatMap(o => checkOccasion(o, { people }));
  const merc = people.find(p => p.id === 'mercurius');
  errs.push(...checkPerson({ ...merc, praise: seed.praises.mercurius }, { cats: { [merc.cat]: 'x' }, statusTyped: false }));
  if (errs.length) throw new Error('the list has problems:\n' + errs.join('\n'));
  const out = [
    '-- «خبزنا اليومي» P5: «مناسبات كنيستنا» (docs/daily-bread/saints/P5-PLAN.md). Generated by tools/bread-occasions-seed.mjs',
    '-- from daily-bread/saints/occasions-seed.json — do not edit by hand. Additive; a second run changes nothing.',
    "INSERT OR IGNORE INTO settings (key, value, updated_at, updated_by) VALUES ('BREAD_OCCASIONS', '0', 0, 'migration');"
  ];
  seed.occasions.forEach((o, i) => {
    if (o.id === 'redseadiocese') {
      out.push(`UPDATE saints_items SET data = ${q(JSON.stringify(o))}, rev = rev + 1, updated_at = 0, updated_by = ${q(BY)} WHERE kind = 'occasion' AND id = 'redseadiocese' AND json_extract(data, '$.type') IS NULL;`);
      out.push(`INSERT OR IGNORE INTO saints_items (kind, id, ord, data, rev, pub_rev, updated_at, updated_by) VALUES ('occasion', 'redseadiocese', 1, ${q(JSON.stringify(o))}, 1, NULL, 0, ${q(BY)});`);
    } else out.push(`INSERT OR IGNORE INTO saints_items (kind, id, ord, data, rev, pub_rev, updated_at, updated_by) VALUES ('occasion', ${q(o.id)}, ${i + 2}, ${q(JSON.stringify(o))}, 1, NULL, 0, ${q(BY)});`);
  });
  out.push(`UPDATE saints_items SET data = json_set(data, '$.praise', json(${q(JSON.stringify(seed.praises.mercurius))})), rev = rev + 1, updated_at = 0, updated_by = ${q(BY)} WHERE kind = 'person' AND id = 'mercurius' AND json_extract(data, '$.praise.source') LIKE ${q('%' + OLD_PRAISE + '%')};`);
  return out.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const seed = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  const people = JSON.parse(fs.readFileSync(path.join(ROOT, 'daily-bread', 'data', 'saints.json'), 'utf8')).people;
  const sql = seedSql(seed, people);
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== sql) { console.error('0037_occasions.sql is not the list: run node tools/bread-occasions-seed.mjs'); process.exit(1); }
    console.log('0037_occasions.sql = the list ✓');
  } else { fs.writeFileSync(OUT, sql); console.log('wrote', path.relative(ROOT, OUT), seed.occasions.length, 'occasions'); }
}
