#!/usr/bin/env node
/*
 * «خبزنا اليومي» P3 — the one-time seed of D1 from P2's registry (daily-bread/saints/registry.json).
 *
 *   node bread-saints-seed.mjs            → worker/migrations/0036_saints_seed.sql
 *   node bread-saints-seed.mjs --check    the migration in the repo is the registry (exit 1 if not)
 *
 * INSERT OR IGNORE, one statement a row (D1 keeps each statement small): applied once with the migrations; run again
 * it changes nothing, and nothing the admin saved is overwritten. status/missing are computed here (withStatus), the
 * same way the Worker computes them on every save. After this, D1 is the registry; P2's file stays as history.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { load, check, withStatus } from './lib/saints.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(ROOT, 'worker', 'migrations', '0036_saints_seed.sql');
const BY = 'P2 import';

const q = s => "'" + String(s).replace(/'/g, "''") + "'";

export function seedSql(reg) {
  const errs = check(reg, { root: ROOT });
  if (errs.length) throw new Error('the registry has problems:\n' + errs.join('\n'));
  const rows = [];
  const row = (kind, id, ord, data) => rows.push(`INSERT OR IGNORE INTO saints_items (kind, id, ord, data, rev, pub_rev, updated_at, updated_by) VALUES (${q(kind)}, ${q(id)}, ${ord}, ${q(JSON.stringify(data))}, 1, NULL, 0, ${q(BY)});`);
  row('meta', 'categories', 0, reg.categories);
  if (reg.about) row('meta', 'about', 1, reg.about);
  if (reg.picturesRoot) row('meta', 'picturesRoot', 2, reg.picturesRoot);
  reg.people.forEach((p, i) => row('person', p.id, i + 1, withStatus(p)));
  (reg.occasions || []).forEach((o, i) => row('occasion', o.id, i + 1, o));
  return [
    '-- «خبزنا اليومي» P3: the one-time seed of saints_items from P2\'s registry (daily-bread/saints/registry.json).',
    '-- Generated by tools/bread-saints-seed.mjs — do not edit by hand. INSERT OR IGNORE: a second run changes nothing,',
    `-- and nothing saved in the admin is overwritten. ${reg.people.length} people, ${(reg.occasions || []).length} occasions.`,
    ...rows, ''
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const sql = seedSql(load());
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== sql) { console.error('✗ ' + path.relative(ROOT, OUT) + ' is not the registry: run node tools/bread-saints-seed.mjs'); process.exit(1); }
    console.log('✓ the seed is the registry');
  } else {
    fs.writeFileSync(OUT, sql);
    console.log(path.relative(ROOT, OUT) + ': ' + sql.split('\n').filter(l => l.startsWith('INSERT')).length + ' rows, ' + Math.round(sql.length / 1024) + ' KB');
  }
}
