// Builds assets/vendor/firebase-messaging.js: the part of the Firebase JS SDK
// (Apache-2.0, https://github.com/firebase/firebase-js-sdk) that web push
// needs, tree-shaken to the exports below, as one ES module.
//
// The public page never loads it on a first visit: assets/js/push.js imports
// it with import() only when a visitor turns notifications on or off, or
// (at most once a week) to refresh the token of a device that subscribed.
// It talks to two Google hosts only, both allowed in index.html's
// connect-src: firebaseinstallations.googleapis.com, fcmregistrations.googleapis.com.
//
// Also builds admin/vendor/firebase-messaging-admin.js: the same subset for
// the admin app (admin/push.js), with ONE change — Firebase Messaging keeps
// its token in an IndexedDB named 'athanasios-admin-messaging-database'
// instead of 'firebase-messaging-database'. Firebase keys that store by the
// web app id only (the same for both pages), so on one phone a getToken()
// from the admin's own worker would otherwise find the visitor token, revoke
// it and replace it (and the site would do the same back). Separate
// databases = separate tokens, both kept.
//
// Run after changing the version in tools/package.json or the list below:
//   cd tools && npm run build-push-vendor

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { ROOT } from './lib/gs.mjs';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');

/* what assets/js/push.js and admin/push.js use (keep in sync) */
export const PUSH_VENDOR_EXPORTS = {
  'firebase/app': ['initializeApp'],
  'firebase/messaging': ['getMessaging', 'getToken', 'deleteToken', 'isSupported']
};

export const ADMIN_MESSAGING_DB = 'athanasios-admin-messaging-database';

const PUBLIC_DB = "'firebase-messaging-database'";

/* esbuild: @firebase/messaging with its token database renamed (in exactly one place, or the build fails) */
function adminDatabase(counter) {

  return {
    name: 'admin-messaging-database',
    setup(build) {
      build.onLoad({ filter: /[\\/]@firebase[\\/]messaging[\\/]dist[\\/]esm[\\/][^\\/]+\.js$/ }, args => {
        const text = readFileSync(args.path, 'utf8');
        const count = text.split(PUBLIC_DB).length - 1;
        if (!count) return undefined;
        if (count !== 1) throw new Error(`${args.path}: expected one ${PUBLIC_DB}, found ${count}`);
        counter.renamed++;
        return { contents: text.replace(PUBLIC_DB, `'${ADMIN_MESSAGING_DB}'`), loader: 'js' };
      });
    }
  };

}

export async function buildPushVendor({ admin = false } = {}) {

  const pkg = JSON.parse(readFileSync(`${ROOT}tools/node_modules/firebase/package.json`, 'utf8'));
  const contents = Object.entries(PUSH_VENDOR_EXPORTS)
    .map(([from, names]) => `export { ${names.join(', ')} } from '${from}';`)
    .join('\n');
  const counter = { renamed: 0 };

  const result = await esbuild.build({
    stdin: { contents, resolveDir: `${ROOT}tools`, loader: 'js' },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    write: false,
    plugins: admin ? [adminDatabase(counter)] : []
  });

  if (admin && counter.renamed !== 1) {
    throw new Error('admin vendor: the messaging token database was not renamed (did Firebase change?)');
  }

  const names = Object.values(PUSH_VENDOR_EXPORTS).flat().join(', ');
  const notice = `/*! Firebase JS SDK ${pkg.version} (subset: ${names}) | Apache-2.0 | https://github.com/firebase/firebase-js-sdk\n` +
    (admin
      ? ` * Admin copy: token database '${ADMIN_MESSAGING_DB}'. Generated by tools/build-push-vendor.mjs. Loaded on demand by admin/push.js. Do not edit by hand. */\n`
      : ' * Generated by tools/build-push-vendor.mjs. Loaded on demand by assets/js/push.js. Do not edit by hand. */\n');

  return { code: notice + result.outputFiles[0].text, version: pkg.version };

}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {

  const { code, version } = await buildPushVendor();
  mkdirSync(`${ROOT}assets/vendor`, { recursive: true });
  writeFileSync(`${ROOT}assets/vendor/firebase-messaging.js`, code);
  console.log(`assets/vendor/firebase-messaging.js written (Firebase ${version}, ${Math.round(code.length / 1024)} KB).`);

  const admin = await buildPushVendor({ admin: true });
  mkdirSync(`${ROOT}admin/vendor`, { recursive: true });
  writeFileSync(`${ROOT}admin/vendor/firebase-messaging-admin.js`, admin.code);
  console.log(`admin/vendor/firebase-messaging-admin.js written (Firebase ${admin.version}, ${Math.round(admin.code.length / 1024)} KB).`);

}
