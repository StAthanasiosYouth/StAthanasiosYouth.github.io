// Builds worker/src/comp/score.gen.js from apps-script/CompScore.gs: the one grading code
// (pure, no Google services), so the Worker grades exactly as Apps Script did. Run after editing
// CompScore.gs: node tools/build-worker-score.mjs. worker/test/comp-runtime.test.mjs fails when stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const NAMES = ['compNormalizeText_', 'compNumber_', 'compEmpty_', 'compAnswerKey_', 'compValidateAnswers_', 'compGrade_', 'compApplyManual_', 'compRegrade_'];

export function buildScore() {
  const source = readFileSync(ROOT + 'apps-script/CompScore.gs', 'utf8').replace(/\r\n/g, '\n');
  return `// GENERATED by tools/build-worker-score.mjs from apps-script/CompScore.gs. Do not edit by hand.\n${source}\nexport { ${NAMES.join(', ')} };\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(ROOT + 'worker/src/comp/score.gen.js', buildScore());
  console.log('worker/src/comp/score.gen.js');
}
