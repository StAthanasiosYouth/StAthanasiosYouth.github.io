// Builds worker/src/content/gs.gen.js: the Apps Script admin code (apps-script/*.gs) as ONE ES module
// factory, so the Worker runs the SAME validation, ids, ordering and home-card rules the Sheets admin
// runs today (Phase 4 P4-2/P4-3, docs/CONTENT-MIGRATION-PLAN.md §6). The Worker gives it its services
// (src/content/runtime.js): sheets held in memory from D1, a cache, the actor, the time.
//
//   createGs(services, init) → { fnName: function, … } — a fresh copy per request (no state leaks).
//   init.set(name, value) assigns one of SETTABLE (module globals the Worker sets per request).
//   init.use(name, fn) replaces one of REPLACEABLE (the few calls that leave the spreadsheet).
//
// Run after changing any of FILES:  cd tools && node build-worker-gs.mjs
// worker/test/content-saves.test.mjs fails when the file is stale.

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { ROOT } from './lib/gs.mjs';

// the files the fake Apps Script world loads (tests/fakes/gas.mjs): every cross-file call resolves
export const FILES = ['Platforms.gs', 'Content.gs', 'Hub.gs', 'Review.gs', 'Seed.gs', 'Auth.gs', 'Store.gs', 'Publish.gs', 'Code.gs', 'Media.gs',
  'Items.gs', 'Import.gs', 'Migrate.gs', 'Presence.gs', 'Activity.gs', 'AdminDevice.gs', 'CompStore.gs', 'CompModel.gs',
  'BookModel.gs', 'Pages.gs', 'WorkerSync.gs', 'PayDest.gs', 'Grants.gs', 'NotifyClaim.gs', 'AdminPlatform.gs', 'AdminNotify.gs', 'Api.gs', 'Push.gs', 'ContentExport.gs'];

const SERVICES = ['SpreadsheetApp', 'CacheService', 'LockService', 'PropertiesService', 'Utilities', 'Session', 'UrlFetchApp',
  'HtmlService', 'ContentService', 'DriveApp', 'ScriptApp', 'console'];

export const SETTABLE = ['API_REQUEST_'];

// module constants the Worker reads (get)
export const READABLE = ['CONTENT_EXPORT_KINDS', 'DATA_SCHEMA_VERSION', 'COMP_SCHEMA_VERSION', 'API_PERMS', 'ACTIVITY_COLUMNS', 'ACTIVITY_MERGE_MS', 'ACTIVITY_MERGE_LOOKBACK'];

// left the spreadsheet in Apps Script; the Worker answers them itself (runtime.js)
export const REPLACEABLE = ['assertAdmin_', 'currentEmail_', 'log_', 'rememberActivity_', 'activityForward_', 'activityPendingFlag_',
  'activityDispatch_', 'apiStateFor_', 'payDestSync_', 'workerSyncSoon_', 'grantsFresh_', 'adminDirectory_', 'displayName_',
  // the review and the publish (P4-4, P4-6): what is live, the competitions' part, where the files go
  'workerLiveContent_', 'publishMode_', 'compDraft_', 'compBuildPublic_', 'compPublishFiles_', 'compReviewInfo_', 'compWriteSnapshots_',
  'compAfterCommit_', 'publishClaim_', 'publishDropClaim_', 'mediaForPublish_', 'githubCommitFiles_', 'publishToWorker_', 'publishShadow_',
  'fetchPublishedContent_', 'lastPublished_',
  // the media library's bytes (P4-5): R2 instead of Drive
  'driveUpload_', 'driveDownloadBase64_', 'drive_'];

// called by bundled code, defined in files that stay on Apps Script: a no-op here unless the Worker replaces it
//   compEnsureSecrets_ (CompCrypto.gs) — Pages.gs pagesWrite_ makes the competitions' secrets; they stay Apps Script's (Phase 5–6)
//   compPublishFiles_, compReviewInfo_, compWriteSnapshots_, compAfterCommit_ (CompPublish.gs) — the competitions' part
//     of a publish is built by Apps Script (apps-script/WorkerComp.gs); the Worker hands over what it answered
//   compShellText_ (CompPublish.gs) — publishNow_ reads the competitions' shell for their files; Apps Script did that already
export const STUBS = ['compEnsureSecrets_', 'compPublishFiles_', 'compReviewInfo_', 'compWriteSnapshots_', 'compAfterCommit_', 'compShellText_'];

export function build() {
  const parts = [];
  const names = new Set();
  for (const file of FILES) {
    // LF whatever the checkout: the source hash is the same on Windows and in CI
    const code = readFileSync(`${ROOT}apps-script/${file}`, 'utf8').replace(/\r\n/g, '\n');
    for (const m of code.matchAll(/^function ([A-Za-z_$][\w$]*)\s*\(/gm)) names.add(m[1]);
    parts.push(`/* ---- apps-script/${file} ---- */\n${code}`);
  }
  const hash = createHash('sha256').update(parts.join('\n')).digest('hex').slice(0, 16);
  for (const n of STUBS) names.add(n);
  const replaceable = REPLACEABLE.filter(n => names.has(n));
  const out = `// GENERATED by tools/build-worker-gs.mjs from apps-script/{${FILES.join(',')}} — source ${hash}.
// Do not edit: change apps-script/ and run \`cd tools && node build-worker-gs.mjs\`.
/* eslint-disable */
export const GS_SOURCE = '${hash}';

export function createGs(__services, __init) {
  var ${SERVICES.map(s => `${s} = __services.${s}`).join(', ')};

${parts.join('\n\n')}

  /* ---- not bundled (STUBS) ---- */
${STUBS.map(n => `  function ${n}() {}`).join('\n')}

  /* ---- Worker hooks ---- */
  if (__init) {
    __init({
      set: function (name, value) {
        switch (name) {
${SETTABLE.map(n => `          case '${n}': ${n} = value; return;`).join('\n')}
        }
        throw new Error('not settable: ' + name);
      },
      use: function (name, fn) {
        switch (name) {
${replaceable.map(n => `          case '${n}': ${n} = fn; return;`).join('\n')}
        }
        throw new Error('not replaceable: ' + name);
      },
      get: function (name) {
        switch (name) {
${SETTABLE.concat(READABLE).map(n => `          case '${n}': return ${n};`).join('\n')}
        }
        throw new Error('not readable: ' + name);
      }
    });
  }

  return {
${[...names].map(n => `    ${n}: ${n}`).join(',\n')}
  };
}
`;
  return { text: out, hash };
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, '/').replace(/^([A-Za-z]):/, '/$1:')}` || process.argv[1].endsWith('build-worker-gs.mjs')) {
  const { text, hash } = build();
  writeFileSync(`${ROOT}worker/src/content/gs.gen.js`, text);
  console.log(`worker/src/content/gs.gen.js: ${(text.length / 1024).toFixed(0)} KB, source ${hash}`);
}
