#!/usr/bin/env node
/*
 * «خبزنا اليومي» P5b — confirming the reviewed praises at once (owner 2026-11-25: «اعتمدهم بشكل جماعي»)
 * → daily-bread/saints/praises-approve.json (the decisions, with the texts fetched now) + worker/migrations/0040_praises_approve.sql.
 *
 * The owner's rules: confirm every candidate that has its full text and is truly about its own person; for a link
 * only, fetch the full text from that source (tools/bread-praise-fetch.mjs) and confirm it; never a praise of another
 * person with a like name, never a text made up or finished by hand; what he edited himself stays as he left it.
 *   - each of the 58 with a text: its words name the person (tools check + read by eye: «ديسقوروس», «آفا بافلي»)
 *   - fetched now: George's doxology, St Macarius the Alexandrian's doxology, the Three Youths' «تين أوويه إنسوك»
 *   - left a candidate, with why (KEEP below)
 * SQL: only a praise exactly as the seed left it (anything the owner changed in it → left alone), at its place, with its id and title, still a candidate; a «main» one only while the person has
 * no confirmed main (else it is left for the owner). rev + 1, so «راجع وانشر» shows them. Nothing else is touched.
 *
 *   node tools/bread-praise-approve.mjs           fetch + write both     --check   the migration is the decisions
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchText } from './bread-praise-fetch.mjs';
import { checkPerson } from '../worker/src/bread/saints.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SEED = path.join(ROOT, 'daily-bread', 'saints', 'praises-seed.json');
const OUT = path.join(ROOT, 'daily-bread', 'saints', 'praises-approve.json');
const SQL = path.join(ROOT, 'worker', 'migrations', '0040_praises_approve.sql');
const q = s => "'" + String(s).replace(/'/g, "''") + "'";

// link only: fetched from the source now (and read: the right person, the whole text as the page gives it)
const FETCH = {
  'george/pr2': 'https://st-takla.org/lyrics/ar/rituals/doxologies/george.html',
  'macariusalex/pr1': 'https://tasbeha.org/hymn_library/view/1893',
  'threeyouths/pr1': 'https://tasbeha.org/hymn_library/view/110'
};
// left for the owner, and why
export const KEEP = {
  'abanoub/pr2': 'الصفحة (athanasiusdeacons) مفيهاش نص نضيف يتقري',
  'anthony/pr1': 'صفحة الأنبا تكلا اتشالت (410) ومفيش نسخة لنفس المديح',
  'bishoy/pr1': 'صفحة الأنبا تكلا اتشالت (410) ومفيش نسخة لنفس المديح',
  'marina/pr1': 'صفحة الأنبا تكلا اتشالت (410)، والموجود هناك مديح تاني',
  'reweis/pr1': 'صفحة الأنبا تكلا اتشالت (410) ومفيش نسخة لنفس التمجيد',
  'simon/pr1': 'صفحة الأنبا تكلا اتشالت (410) ومفيش نسخة لنفس المديح',
  'maximus/pr1': 'tasbeha.org مفيهوش النص العربي للذكصولوجية دي',
  'peterpaul/pr1': 'التمجيد هباشي على عمودين في الصفحة، وترتيب الأبيات محتاج عينك',
  'peterpaul/pr2': 'الصفحة (athanasiusdeacons) مفيهاش نص نضيف يتقري',
  'sarapamonabutarha/pr1': 'الصفحة (orsozox) مفيهاش نص نضيف يتقري',
  'threeyouths/pr2': 'الرابط بيفتح إبصالية القيامة («يسوع المسيح قام») مش إبصالية الثلاثة فتية'
};

export function approveSql(decisions) {
  const out = [
    '-- «خبزنا اليومي» P5b: the reviewed praises confirmed at once (owner 2026-11-25). Generated by tools/bread-praise-approve.mjs',
    '-- from daily-bread/saints/praises-approve.json — do not edit by hand. Only a praise still a candidate, at its place,',
    '-- with its id and title; a main one only while the person has no confirmed main. A second run changes nothing.'
  ];
  for (const d of decisions) {
    const at = `$.praises[${d.at}]`;
    let set = `json_set(data, '${at}.status', 'confirmed')`;
    if (d.verses) set = `json_set(${set}, '${at}.verses', json(${q(JSON.stringify(d.verses))}), '${at}.opening', ${q(d.verses[0][0])})`;
    const noMain = d.main ? ` AND NOT EXISTS (SELECT 1 FROM json_each(saints_items.data, '$.praises') AS j WHERE json_extract(j.value, '$.status') = 'confirmed' AND json_extract(j.value, '$.main') = 1)` : '';
    out.push(`UPDATE saints_items SET data = ${set}, rev = rev + 1, updated_at = 0, updated_by = 'P5b approve' WHERE kind = 'person' AND id = ${q(d.person)} AND json_extract(data, '${at}.id') = ${q(d.id)} AND json_extract(data, '${at}.title') = ${q(d.title)} AND json_extract(data, '${at}.status') = 'candidate' AND json_extract(data, '${at}') = json(${q(JSON.stringify(d.was))})${noMain};`);
  }
  return out.join('\n') + '\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const sql = approveSql(JSON.parse(fs.readFileSync(OUT, 'utf8')).decisions);
    if (fs.readFileSync(SQL, 'utf8').replace(/\r\n/g, '\n') !== sql) { console.error('0040 is not the decisions: run node tools/bread-praise-approve.mjs'); process.exit(1); }
    console.log('0040_praises_approve.sql = the decisions ✓');
  } else {
    const seed = JSON.parse(fs.readFileSync(SEED, 'utf8')).praises;
    const reg = JSON.parse(fs.readFileSync(path.join(ROOT, 'daily-bread', 'data', 'saints.json'), 'utf8'));
    const decisions = [], errs = [];
    // what the owner reviewed by hand on Production (2026-11-25, all confirmed by him): not touched
    const OWNER_DONE = ['mary', 'gabriel', 'michael'];
    for (const [person, list] of Object.entries(seed)) {
      if (OWNER_DONE.includes(person)) continue;
      const p = structuredClone(reg.people.find(x => x.id === person));
      for (const m of p.milestones || []) if (!m.status) m.status = 'confirmed';
      p.praises = structuredClone(list);
      for (const [at, it] of list.entries()) {
        const key = person + '/' + it.id;
        if (it.status !== 'candidate' || KEEP[key]) continue;
        let verses = null;
        if (!it.verses) {
          if (!FETCH[key]) { errs.push(key + ': no text and not in FETCH/KEEP'); continue; }
          const t = await fetchText(FETCH[key]);
          if (!t) { errs.push(key + ': the source gave no text'); continue; }
          verses = t.verses;
          p.praises[at].verses = verses;
          p.praises[at].source = it.source;
        }
        p.praises[at].status = 'confirmed';
        decisions.push({ person, at, id: it.id, title: it.title, was: it, ...(it.main ? { main: true } : {}), ...(verses ? { verses, from: FETCH[key] } : {}) });
      }
      // two confirmed mains in the seed's own state → the main one waits (the SQL guard does the same on the live data)
      errs.push(...checkPerson(p, { cats: { [p.cat]: 'x' }, statusTyped: false }).map(e => person + ': ' + e));
    }
    if (errs.length) { console.error(errs.join('\n')); process.exit(1); }
    fs.writeFileSync(OUT, JSON.stringify({ about: 'P5b: the praises confirmed at once (owner 2026-11-25). keep = left a candidate, with why.', keep: KEEP, decisions }, null, 1) + '\n');
    fs.writeFileSync(SQL, approveSql(decisions));
    console.log(decisions.length, 'confirmed (' + decisions.filter(d => d.verses).length + ' with text fetched now),', Object.keys(KEEP).length, 'left a candidate');
  }
}
