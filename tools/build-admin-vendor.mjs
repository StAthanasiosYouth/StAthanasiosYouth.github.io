// Builds admin/vendor/mediabunny.js: the part of Mediabunny (MPL-2.0,
// https://mediabunny.dev) the admin's video trimmer uses, tree-shaken to the
// exports below, as one ES module. Admin only: the page imports it with
// import() when the admin chooses a video (apps-script/AdminTrim.html); the
// public site never loads it.
//
// Run after changing the version in tools/package.json or the list below:
//   cd tools && npm run build-vendor

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { ROOT } from './lib/gs.mjs';

const require = createRequire(import.meta.url);
const esbuild = require('esbuild');

/* what AdminTrim.html uses (keep in sync) */
export const VENDOR_EXPORTS = [
  'Input', 'BlobSource', 'MP4', 'QTFF', 'MATROSKA', 'WEBM', 'VideoSampleSink',
  'Output', 'Mp4OutputFormat', 'BufferTarget', 'CanvasSource', 'canEncodeVideo'
];

export async function buildVendor() {

  const pkg = JSON.parse(readFileSync(`${ROOT}tools/node_modules/mediabunny/package.json`, 'utf8'));
  const result = await esbuild.build({
    stdin: {
      contents: `export { ${VENDOR_EXPORTS.join(', ')} } from 'mediabunny';\n`,
      resolveDir: `${ROOT}tools`,
      loader: 'js'
    },
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2020',
    minify: true,
    legalComments: 'none',
    write: false
  });

  const notice = `/*! Mediabunny ${pkg.version} (subset: ${VENDOR_EXPORTS.join(', ')}) | MPL-2.0 | https://github.com/Vanilagy/mediabunny\n` +
    ' * Source: the npm package "mediabunny"; license: mediabunny.LICENSE.txt next to this file.\n' +
    ' * Generated by tools/build-admin-vendor.mjs. Admin only. Do not edit by hand. */\n';

  return { code: notice + result.outputFiles[0].text, version: pkg.version };

}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {

  const { code, version } = await buildVendor();
  mkdirSync(`${ROOT}admin/vendor`, { recursive: true });
  writeFileSync(`${ROOT}admin/vendor/mediabunny.js`, code);
  copyFileSync(`${ROOT}tools/node_modules/mediabunny/LICENSE`, `${ROOT}admin/vendor/mediabunny.LICENSE.txt`);
  console.log(`admin/vendor/mediabunny.js written (Mediabunny ${version}, ${Math.round(code.length / 1024)} KB).`);

}
